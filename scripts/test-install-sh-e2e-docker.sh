#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGE_NAME="${OPENCLAWCN_INSTALL_E2E_IMAGE:-openclawcn-install-e2e:local}"
INSTALL_URL="${OPENCLAWCN_INSTALL_URL:-https://openclawcn.com/install.sh}"

OPENAI_API_KEY="${OPENAI_API_KEY:-}"
ANTHROPIC_API_KEY="${ANTHROPIC_API_KEY:-}"
ANTHROPIC_API_TOKEN="${ANTHROPIC_API_TOKEN:-}"
OPENCLAWCN_E2E_MODELS="${OPENCLAWCN_E2E_MODELS:-}"

echo "==> Build image: $IMAGE_NAME"
docker build \
  -t "$IMAGE_NAME" \
  -f "$ROOT_DIR/scripts/docker/install-sh-e2e/Dockerfile" \
  "$ROOT_DIR/scripts/docker/install-sh-e2e"

echo "==> Run E2E installer test"
docker run --rm \
  -e OPENCLAWCN_INSTALL_URL="$INSTALL_URL" \
  -e OPENCLAWCN_INSTALL_TAG="${OPENCLAWCN_INSTALL_TAG:-latest}" \
  -e OPENCLAWCN_E2E_MODELS="$OPENCLAWCN_E2E_MODELS" \
  -e OPENCLAWCN_INSTALL_E2E_PREVIOUS="${OPENCLAWCN_INSTALL_E2E_PREVIOUS:-}" \
  -e OPENCLAWCN_INSTALL_E2E_SKIP_PREVIOUS="${OPENCLAWCN_INSTALL_E2E_SKIP_PREVIOUS:-0}" \
  -e OPENAI_API_KEY="$OPENAI_API_KEY" \
  -e ANTHROPIC_API_KEY="$ANTHROPIC_API_KEY" \
  -e ANTHROPIC_API_TOKEN="$ANTHROPIC_API_TOKEN" \
  "$IMAGE_NAME"
