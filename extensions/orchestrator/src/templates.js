function listTemplates() {
  return BUILTIN_TEMPLATES;
}
function getTemplate(id) {
  return BUILTIN_TEMPLATES.find((t) => t.id === id);
}
function matchTemplate(requirement) {
  const lowerReq = requirement.toLowerCase();
  let bestMatch;
  let bestScore = 0;
  for (const template of BUILTIN_TEMPLATES) {
    const keywords = template.keywords ?? [];
    let score = 0;
    for (const keyword of keywords) {
      if (lowerReq.includes(keyword.toLowerCase())) {
        score++;
      }
    }
    if (lowerReq.includes(template.name)) score += 3;
    if (lowerReq.includes(template.id)) score += 2;
    if (score > bestScore) {
      bestScore = score;
      bestMatch = template;
    }
  }
  return bestScore >= 2 ? bestMatch : void 0;
}
function formatTemplateList(templates) {
  if (templates.length === 0) return "No templates available.";
  const lines = ["## Available Templates\n"];
  for (const t of templates) {
    lines.push(`### ${t.emoji ?? "\u{1F4E6}"} ${t.name} (\`${t.id}\`)`);
    lines.push(t.description);
    if (t.highlights?.length) {
      lines.push(`- Highlights: ${t.highlights.join(" / ")}`);
    }
    lines.push(`- Agents: ${t.agents.map((a) => `${a.emoji ?? "\u{1F916}"} ${a.name}`).join(", ")}`);
    lines.push(
      `- Default model tier: ${t.defaultModelTier ?? "mid"}`
    );
    lines.push("");
  }
  return lines.join("\n");
}
