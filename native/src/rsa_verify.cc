// Key registry: try v2 first, then v1
struct KeyEntry {
  const uint8_t* data;
  size_t len;
};
static const KeyEntry kKeyEntries[] = {
  { kRsaPublicKeyV2Enc, kRsaPublicKeyV2EncLen },
  { kRsaPublicKeyV1Enc, kRsaPublicKeyV1EncLen },
};
static const size_t kKeyCount = sizeof(kKeyEntries) / sizeof(kKeyEntries[0]);

/**
 * Decrypt an embedded PEM key at runtime (XOR with kXorKey).
 * Caller must wipe the returned string via wipePemKey() after use.
 */
static std::string decryptPemKey(const uint8_t* encData, size_t encLen) {
  std::string pem(encLen, '\0');
  for (size_t i = 0; i < encLen; i++) {
    pem[i] = static_cast<char>(encData[i] ^ kXorKey[i % kXorKeyLen]);
  }
  return pem;
}

/**
 * Securely wipe a string (volatile to prevent compiler optimization)
 */
static void wipePemKey(std::string& s) {
  volatile char* p = &s[0];
  for (size_t i = 0; i < s.size(); i++) {
    p[i] = '\0';
  }
  s.clear();
}

/**
 * Decode base64 to binary
 */
static std::vector<uint8_t> base64Decode(const std::string& b64) {
  BIO* bio = BIO_new_mem_buf(b64.data(), static_cast<int>(b64.size()));
  BIO* b64bio = BIO_new(BIO_f_base64());
  bio = BIO_push(b64bio, bio);
  BIO_set_flags(bio, BIO_FLAGS_BASE64_NO_NL);

  std::vector<uint8_t> result(b64.size()); // over-allocate
  int len = BIO_read(bio, result.data(), static_cast<int>(result.size()));
  BIO_free_all(bio);

  if (len > 0) {
    result.resize(static_cast<size_t>(len));
  } else {
    result.clear();
  }
  return result;
}

/**
 * Try to verify a signature with a single PEM key.
 */
static bool verifyWithKey(const std::string& signContent,
                           const std::vector<uint8_t>& sigBytes,
                           const uint8_t* encData, size_t encLen) {
  std::string pemKey = decryptPemKey(encData, encLen);

  BIO* keyBio = BIO_new_mem_buf(pemKey.data(),
                                 static_cast<int>(pemKey.size()));
  if (!keyBio) {
    wipePemKey(pemKey);
    return false;
  }

  EVP_PKEY* pubKey = PEM_read_bio_PUBKEY(keyBio, nullptr, nullptr, nullptr);
  BIO_free(keyBio);
  wipePemKey(pemKey);

  if (!pubKey) {
    return false;
  }

  EVP_MD_CTX* mdCtx = EVP_MD_CTX_new();
  if (!mdCtx) {
    EVP_PKEY_free(pubKey);
    return false;
  }

  bool valid = false;
  if (EVP_DigestVerifyInit(mdCtx, nullptr, EVP_sha256(), nullptr, pubKey) == 1) {
    if (EVP_DigestVerifyUpdate(mdCtx,
                                signContent.data(),
                                signContent.size()) == 1) {
      int rc = EVP_DigestVerifyFinal(mdCtx, sigBytes.data(), sigBytes.size());
      valid = (rc == 1);
    }
  }

  EVP_MD_CTX_free(mdCtx);
  EVP_PKEY_free(pubKey);
  return valid;
}

bool RsaVerify::verify(const std::string& signContent,
                        const std::string& signature) {
  std::vector<uint8_t> sigBytes = base64Decode(signature);
  if (sigBytes.empty()) {
    return false;
  }

  // Dual-key fallback: try each key in order, first match wins
  for (size_t i = 0; i < kKeyCount; i++) {
    if (verifyWithKey(signContent, sigBytes,
                      kKeyEntries[i].data, kKeyEntries[i].len)) {
      return true;
    }
  }

  return false;
}

bool RsaVerify::isKeyConfigured() {
  // Check if any embedded key matches a known fingerprint
  const char* fingerprints[] = { "kDtHShdtjfCopovpCcIR", "uB00UMEJdP/XxmCJ" };
  for (size_t i = 0; i < kKeyCount; i++) {
    std::string pemKey = decryptPemKey(kKeyEntries[i].data, kKeyEntries[i].len);
    for (const char* fp : fingerprints) {
      if (pemKey.find(fp) != std::string::npos) {
        wipePemKey(pemKey);
        return true;
      }
    }
    wipePemKey(pemKey);
  }
  return false;
}

std::string RsaVerify::getKeyFingerprint() {
  // Return fingerprints of all configured keys
  const char* fingerprints[] = { "uB00UMEJdP/XxmCJ", "kDtHShdtjfCopovpCcIR" };
  for (size_t i = 0; i < kKeyCount; i++) {
    std::string pemKey = decryptPemKey(kKeyEntries[i].data, kKeyEntries[i].len);
    for (const char* fp : fingerprints) {
      if (pemKey.find(fp) != std::string::npos) {
        wipePemKey(pemKey);
        return std::string(fp);
      }
    }
    wipePemKey(pemKey);
  }
  return std::string("unknown");
}

// --- N-API Exports ---

Napi::Value RsaVerify::VerifySignature(const Napi::CallbackInfo& info) {
  Napi::Env env = info.Env();

  if (info.Length() < 2 || !info[0].IsString() || !info[1].IsString()) {
    Napi::TypeError::New(env, "Expected (signContent: string, signature: string)")
        .ThrowAsJavaScriptException();
    return env.Null();
  }

  std::string signContent = info[0].As<Napi::String>().Utf8Value();
  std::string signature = info[1].As<Napi::String>().Utf8Value();

  bool result = verify(signContent, signature);
  return Napi::Boolean::New(env, result);
}

Napi::Value RsaVerify::IsKeyConfigured(const Napi::CallbackInfo& info) {
  return Napi::Boolean::New(info.Env(), isKeyConfigured());
}

